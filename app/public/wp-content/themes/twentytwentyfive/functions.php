if ( ! function_exists( 'twentytwentyfive_register_block_bindings' ) ) :
	/**
	 * Registers the post format block binding source.
	 *
	 * @since Twenty Twenty-Five 1.0
	 *
	 * @return void
	 */
	function twentytwentyfive_register_block_bindings() {
		register_block_bindings_source(
			'twentytwentyfive/format',
			array(
				'label'              => _x( 'Post format name', 'Label for the block binding placeholder in the editor', 'twentytwentyfive' ),
				'get_value_callback' => 'twentytwentyfive_format_binding',
			)
		);
	}
endif;
add_action( 'init', 'twentytwentyfive_register_block_bindings' );

if ( ! function_exists( 'twentytwentyfive_format_binding' ) ) :
	/**
	 * Callback function for the post format name block binding source.
	 *
	 * @since Twenty Twenty-Five 1.0
	 *
	 * @return string|void Post format name, or nothing if the format is 'standard'.
	 */
	function twentytwentyfive_format_binding() {
		$post_format_slug = get_post_format();

		if ( $post_format_slug && 'standard' !== $post_format_slug ) {
			return get_post_format_string( $post_format_slug );
		}
	}
endif;
// Register Document CPT
function register_document_cpt() {
    register_post_type('document', [
        'labels' => [
            'name' => 'Documents',
            'singular_name' => 'Document',
            'add_new' => 'Add New',
            'add_new_item' => 'Add New Document',
            'edit_item' => 'Edit Document',
            'new_item' => 'New Document',
            'view_item' => 'View Document',
            'search_items' => 'Search Documents',
            'not_found' => 'No documents found',
        ],
        'public' => true,
        'has_archive' => false,
        'show_in_rest' => true,
        'rest_base' => 'documents',
        'rewrite' => ['slug' => 'documents'],
        'supports' => ['title'],
        'menu_icon' => 'dashicons-media-document',
    ]);
}
add_action('init', 'register_document_cpt');

// Show all users in REST API regardless of post count
add_filter('rest_user_query', 'show_all_users_in_rest');
function show_all_users_in_rest($prepared_args) {
    $prepared_args['has_published_posts'] = false;
    return $prepared_args;
}

// Expose email in REST API for authenticated users
add_action('rest_api_init', function() {
    register_rest_field('user', 'email', [
        'get_callback' => function($user_obj) {
            if (is_user_logged_in()) {
                $user = get_userdata($user_obj['id']);
                return $user ? $user->user_email : '';
            }
            return '';
        },
        'update_callback' => null,
        'schema' => null,
    ]);
});